package com.operators;
//Write a Java program to demonstrate all relational operators (==, !=, >, <, >=, <=) 
//using two decimal numbers?
public class Relational_Opr {

	public static void main(String[] args) {
		int a=12;
		int b=40;
		
		System.out.println("Comparision operator:"+(a==b));
		System.out.println("Not equals to operator:" +(a!=b));
		System.out.println("Greater than operator:"+(a>b));
		System.out.println("Less than operator:"+(a<b));
		System.out.println("Less than or equals to operator:"+(a<=b));
		System.out.println("Greater than or equals to operator:"+(a>=b));
		

	}

}
