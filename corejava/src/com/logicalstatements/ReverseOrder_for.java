package com.logicalstatements;
//1. Write a Java program to print numbers from 1 to 10 in reverse order using a for loop?

public class ReverseOrder_for {

	public static void main(String[] args) {

		System.out.println("Main method started");
		for(int i=10;i>=0;i--) {
			System.out.println(i);
		}
	}

}
